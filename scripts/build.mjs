#!/usr/bin/env node
/**
 * Build this surface package's page from src/preview.html and src/main.ts.
 *
 * Usage: node scripts/build.mjs
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const templatePath = path.join(root, "src", "preview.html");
const template = await readFile(templatePath, "utf8");
const placeholder = "<!--bundle-->";
if (template.split(placeholder).length !== 2) {
  throw new Error("src/preview.html must contain exactly one <!--bundle--> marker");
}
const result = await build({
  entryPoints: [path.join(root, "src", "main.ts")],
  bundle: true,
  format: "iife",
  target: "es2022",
  minify: true,
  legalComments: "none",
  write: false,
  logLevel: "silent",
});
const script = result.outputFiles[0]?.text;
if (!script) throw new Error("esbuild produced no script");
const header = "<!-- Generated by scripts/build.mjs from src/preview.html. Edit the sources, not this file. -->\n";
const document = header + template.replace(placeholder, () => script);
const bytes = Buffer.byteLength(document);
if (bytes > 1 << 20) throw new Error(`surface page is ${bytes} bytes, over the 1 MiB host limit`);
const output = path.join(root, "preview.html");
await writeFile(output, document, "utf8");
console.log(`${bytes} bytes → ${path.relative(root, output)}`);
